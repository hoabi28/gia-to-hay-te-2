import type { CommunityReview, Laptop } from "@/types/laptop";
import { generatePriceHistory } from "@/lib/mockPriceHistory";
import { buildStoreOffers } from "@/lib/mockStores";

/**
 * DỮ LIỆU MINH HOẠ — toàn bộ giá, thông số, điểm số và review trong file này
 * là dữ liệu mẫu phục vụ demo giao diện, KHÔNG phải giá/số liệu thực tế trên thị trường.
 * Khi tích hợp API thật, thay thế module này bằng lớp gọi dữ liệu tương ứng,
 * miễn là giữ đúng shape của type `Laptop`.
 */

type ReviewInput = Omit<CommunityReview, "id">;

function mkReviews(productId: string, list: ReviewInput[]): CommunityReview[] {
  return list.map((r, i) => ({ ...r, id: `${productId}-r${i + 1}` }));
}

interface RawLaptopInput extends Omit<Laptop, "priceHistory" | "stores"> {
  listPrice: number;
}

function build(input: RawLaptopInput): Laptop {
  const { listPrice, ...rest } = input;
  const priceHistory = generatePriceHistory({ seed: input.id, listPrice });
  const bestPrice = priceHistory[priceHistory.length - 1].price;
  const stores = buildStoreOffers({
    seed: input.id,
    bestPrice,
    warrantyMonths: input.warrantyMonths,
    storeCount: input.category === "gaming" ? 5 : 4,
  });
  return { ...rest, priceHistory, stores };
}

